DATABASE_URL_SCHEME = "mysql+asyncmy"


def validate_database_driver(database_url: str) -> None:
    """Fail fast with an actionable error when the async MySQL driver is absent."""
    scheme = database_url.split(":", 1)[0].lower()
    if scheme != DATABASE_URL_SCHEME:
        raise ValueError(
            f"DATABASE_ASYNC_DRIVER_INVALID: database_url_scheme={scheme} "
            f"required_scheme={DATABASE_URL_SCHEME}"
        )
    try:
        importlib.import_module("asyncmy")
    except ModuleNotFoundError as error:
        if error.name != "asyncmy":
            raise
        raise RuntimeError(
            "DATABASE_ASYNC_DRIVER_MISSING: driver=asyncmy "
            f"database_url_scheme={scheme} python_executable={sys.executable}"
        ) from error


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", env_prefix="APP_", extra="ignore")
    database_url: str = "mysql+asyncmy://ctf_agent:ctf_agent@localhost:3307/ctf_agent"
    workspace_root: Path = Path("../data/workspaces")
    runner_url: str = "http://192.168.236.128:8091"
    # Global fallback model used when a caller (e.g. an arena connection) has no
    # model of its own. Unset means there is no fallback.
    default_model_config_id: str | None = None
    runner_api_token: str = "development-runner-token"
    # Shared only with the local run-scoped ctfctl MCP subprocess. It is not
    # included in browser responses or model context.
    ctfctl_internal_access_key: str = "development-ctfctl-access-key"
    cors_origins: str = "http://localhost:5173,http://127.0.0.1:5173"
    encryption_key: str = "development-only-change-me"
    allowed_service_cidrs: str = "127.0.0.0/8,192.168.56.0/24,192.168.236.0/24"
    environment: str = "development"
    # Local Kali/WebSocket setups may intentionally route localhost targets
    # through a tunnel. Keep the production default blocked unless explicitly
    # enabled in the environment.
    allow_remote_local_targets: bool = False
    codex_diagnostic_mode: bool = False
    historical_lesson_mode: str = "strategy_only"
    #: Whether ``AGENTS.md`` opens with ``FIRST_MOVE_DISCIPLINE`` -- the block
    #: that forces the first hard fact (product+version, CVE id) to become a
    #: concrete exploitation hypothesis before anything else is attempted.
    #:
    #: A flag rather than a straight edit so the change can be measured instead
    #: of assumed: turn it off for the control arm and compare how many steps
    #: pass before the first flag-directed exploit attempt appears.  Leaving it
    #: on by default is deliberate -- the failure it targets (holding evidence
    #: and not committing to it) was present in every long unsolved Run sampled
    #: on 2026-11-05, and the block costs ~1KB of the ``head -50`` window.
    first_move_discipline: bool = True
    web_search_provider: str = "disabled"
    web_search_url: str = ""
    web_search_api_key: str = ""
    web_search_timeout_seconds: int = 20
    # Shared secret demanded by the standalone Claude proxy. Generated by the
    # launcher because that proxy binds 0.0.0.0 (Worker containers must reach it
    # by host alias), so leaving it open would expose the model credentials to
    # the whole LAN. Empty means no check, which is only correct for loopback.
    claude_proxy_token: str = ""
    # Where the proxy writes its random port, so the backend can point a
    # claude_cli Worker at it without the operator copying a number by hand.
    # Defaulted to the same path the launcher uses: both sides must agree on this
    # file or the backend would report "no proxy" while one is plainly running.
    claude_proxy_state_file: str = str(
        Path(__file__).resolve().parents[3] / ".claude-proxy.json"
    )
    # Whether the backend starts the proxy itself. On by default so a Claude
    # channel works without a second terminal; switch off when the proxy is
    # managed externally (systemd, a container) and this process must not
    # compete for the same port and state file.
    claude_proxy_autostart: bool = True
    # Shared secret demanded by the standalone Codex Responses proxy.  The
    # mirror of ``claude_proxy_token``: this proxy also binds 0.0.0.0 so a
    # containerised codex Worker can reach it by host alias, so an unguarded one
    # would let anything on the LAN spend the upstream model credits.
    codex_proxy_token: str = ""
    # Where the Codex proxy writes its random port.  Kept as its own file, not
    # shared with the Claude proxy's: the two are separate processes on separate
    # ports, and one file would make each reader see whichever wrote last.
    codex_proxy_state_file: str = str(
        Path(__file__).resolve().parents[3] / ".codex-proxy.json"
    )
    # Whether the backend starts the Codex proxy itself.  Same reasoning as the
    # Claude one: on by default so a codex channel works without a second
    # terminal, off when the operator runs it under their own supervisor.
    codex_proxy_autostart: bool = True
    # Where the arena's in-flight environment lease is recorded, so a process
    # that dies mid-solve can still destroy the environment it left behind.  The
    # platform allows exactly one environment per agent, so an unreclaimed one
    # blocks every later solve with an error that points somewhere else entirely.
    # A file rather than a table on purpose: it is a single volatile breadcrumb,
    # it must be readable before the database session machinery is warm, and it
    # needs no migration.
    arena_lease_state_file: str = str(
        Path(__file__).resolve().parents[3] / "data" / "arena-lease.json"
    )
    #: Whether the **legacy Kali Runner** is part of this deployment.
    #:
    #: Muteki executes tools in container-native Workers (``container_exec`` and
    #: the official Worker sandbox), so the standalone Runner service is no longer
    #: an execution path -- only a compatibility shim for old code and a settings
    #: field that makes the whole console look unhealthy when the (usually absent)
    #: Kali VM is down.
    #:
    #: ``False`` by default: readiness stops probing it, the settings payload stops
    #: advertising it, and ``tool_manifest`` stops treating "no Runner" as drift.
    #: That last one is the load-bearing part -- the manifest intersected the
    #: effective tool set with the Runner's advertised capabilities, so a down
    #: Runner silently emptied every Run's tool list and paused it with
    #: ``TOOL_CATALOG_DRIFT``.  Set ``APP_LEGACY_KALI_RUNNER=1`` to restore the
    #: old behaviour for a deployment that still fronts a Runner.
    legacy_kali_runner: bool = False
    #: The flag banner the arena platform uses, applied to challenges mirrored
    #: from it.  Established from accepted submissions rather than assumed: every
    #: flag this platform has actually accepted was ``CTF2{<uuid>}``.  Without it
    #: the mirrored challenge keeps the generic ``flag{...}`` default, which never
    #: matches -- and the flag service's permissive fallback then accepts any
    #: ``Xxx{...}`` shape, so a hallucinated flag passed local verification.
    arena_flag_banner: str = "CTF2"
    #: Knowledge recall for arena (batch) solves: ``"on"`` or ``"off"``.
    #:
    #: The arena path builds its Runs through ``create_run`` and never wrote a
    #: ``knowledge_mode`` hint, so every batch solve silently ran with the
    #: deployment default (``C7F_KNOWLEDGE_MODE``, itself defaulting to ``off``)
    #: -- the curated corpus and the distilled templates were never recalled even
    #: though the whole knowledge pipeline was wired and populated.  Defaults to
    #: ``"on"`` because the corpus already exists and is the point of the feature;
    #: set ``APP_ARENA_KNOWLEDGE_MODE=off`` to run the baseline arm of an A/B
    #: comparison without editing code.
    arena_knowledge_mode: Literal["off", "on"] = "on"
    #: Whether the proxy rewrites vendor marks inside an incoming system prompt
    #: before forwarding it upstream.
    #:
    #: The relay in front of the model rejects a request that identifies itself as
    #: an official vendor client while arriving over a non-official channel --
    #: HTTP 400, ``code 11128``, "Illegal API invocation from an unapproved
    #: channel".  The Claude CLI injects such marks into its *own* system prompt
    #: (``You are a Claude agent, built on Anthropic's Claude Agent SDK``), so
    #: every CLI turn is rejected no matter how correct the endpoint, key or
    #: protocol translation is; the symptom is a health probe that fails with no
    #: usable diagnostic.
    #:
    #: Rewriting the marks keeps the turn's meaning while letting it through.
    #: This is a compatibility shim, **not** a security control: it depends on the
    #: relay's current matching rule and stops working if that rule changes.  Turn
    #: it off to get the upstream's own error back verbatim.
    claude_proxy_scrub_vendor_marks: bool = True

    #: Whether outbound HTTP clients honour ``HTTP(S)_PROXY`` from the process
    #: environment.  Default **off**, because that environment is not ours.
    #:
    #: The backend is normally started from an interactive session which has its
    #: own short-lived egress proxy exported (an agent sandbox, a VPN client, a
    #: debugging tunnel).  ``httpx`` reads those variables by default, so every
    #: arena REST call, MCP call and model relay silently inherits a proxy that
    #: dies with the shell that started it.  The visible symptom is not "a proxy
    #: problem": every outbound call turns into
    #: ``ARENA_MCP_UNREACHABLE: All connection attempts failed`` at the connection
    #: layer, hours later, while direct curl from the same host succeeds -- and a
    #: batch of runs is spent before anyone suspects the environment.
    #:
    #: The targets this process talks to (arena REST, MCP endpoint, model relay)
    #: are reachable directly.  Set ``APP_RESPECT_PROXY_ENV=1`` when the host
    #: genuinely needs a proxy to leave the network -- then the variables are
    #: intentional, configured once, and long-lived.
    respect_proxy_env: bool = False

    @field_validator("database_url")
    @classmethod
    def require_mysql_database_url(cls, value: str) -> str:
        if value.split(":", 1)[0].lower() != DATABASE_URL_SCHEME:
            raise ValueError("APP_DATABASE_URL must use mysql+asyncmy")
        return value

    @property
    def platform_database_is_mysql(self) -> bool:
        return self.database_url.split(":", 1)[0].lower() == DATABASE_URL_SCHEME

    # Hotfix feature gates. They deliberately default to off; Codex MCP is
    # enabled for a run only after the explicit preflight succeeds.
    codex_mcp_required: bool = False
    enable_tool_tickets: bool = False
    enable_logical_tool_calls: bool = False
    enable_terminal_generation_guard: bool = False

    @staticmethod
    def _feature_flag(name: str, default: bool = False) -> bool:
        raw = os.getenv(name)
        if raw is None:
            raw = os.getenv(f"APP_{name}")
        return default if raw is None else raw.strip().lower() in {"1", "true", "yes", "on"}

    @property
    def feature_flags(self) -> dict[str, bool]:
        return {
            "CODEX_MCP_REQUIRED": self._feature_flag("CODEX_MCP_REQUIRED", self.codex_mcp_required),
            "ENABLE_TOOL_TICKETS": self._feature_flag("ENABLE_TOOL_TICKETS", self.enable_tool_tickets),
            "ENABLE_LOGICAL_TOOL_CALLS": self._feature_flag("ENABLE_LOGICAL_TOOL_CALLS", self.enable_logical_tool_calls),
            "ENABLE_TERMINAL_GENERATION_GUARD": self._feature_flag("ENABLE_TERMINAL_GENERATION_GUARD", self.enable_terminal_generation_guard),
        }

    def require_safe_production_secrets(self) -> None:
        if not self.platform_database_is_mysql:
            raise RuntimeError("Platform persistence requires a MySQL database URL.")
        if self.environment.lower() not in {"dev", "development", "test", "testing"} and (
            self.runner_api_token == "development-runner-token"
            or self.encryption_key == "development-only-change-me"
        ):
            raise RuntimeError(
                "Default Runner token or encryption key is forbidden outside development."
            )

    @property
    def cors_origin_list(self) -> list[str]:
        return [item.strip() for item in self.cors_origins.split(",") if item.strip()]

    @property
    def codex_diagnostics_enabled(self) -> bool:
        raw = os.getenv("CODEX_DIAGNOSTIC_MODE")
        if raw is not None:
            return raw.strip().lower() in {"1", "true", "yes", "on"}
        return bool(self.codex_diagnostic_mode)


@lru_cache
def get_settings() -> Settings:
    return Settings()


def persist_service_urls(runner_url: str) -> None:
    """Persist only non-secret local service endpoints for the next restart."""
    path = Path(__file__).resolve().parents[2] / ".env"
    values = {"APP_RUNNER_URL": runner_url}
    lines = path.read_text(encoding="utf-8").splitlines() if path.exists() else []
    seen: set[str] = set()
    updated: list[str] = []
    for line in lines:
        key = line.partition("=")[0]
        if key in values:
            updated.append(f"{key}={values[key]}")
            seen.add(key)
        else:
            updated.append(line)
    updated.extend(f"{key}={value}" for key, value in values.items() if key not in seen)
    path.write_text("\n".join(updated) + "\n", encoding="utf-8")


def persist_default_model(model_config_id: str | None) -> None:
    """Persist the global default model id for the next restart.

    ``None`` is written as an empty value rather than the literal ``"None"``:
    an empty APP_DEFAULT_MODEL_CONFIG_ID clears the setting on reload, while
    ``"None"`` would be parsed as a real (non-existent) id.
    """
    path = Path(__file__).resolve().parents[2] / ".env"
    values = {"APP_DEFAULT_MODEL_CONFIG_ID": model_config_id or ""}
    lines = path.read_text(encoding="utf-8").splitlines() if path.exists() else []
    seen: set[str] = set()
    updated: list[str] = []
    for line in lines:
        key = line.partition("=")[0]
        if key in values:
            updated.append(f"{key}={values[key]}")
            seen.add(key)
        else:
            updated.append(line)
    updated.extend(f"{key}={value}" for key, value in values.items() if key not in seen)
    path.write_text("\n".join(updated) + "\n", encoding="utf-8")


def validate_service_host(host: str, allow_private_runner: bool) -> None:
    if host == "localhost":
        return
    try:
        addresses = {item[4][0] for item in socket.getaddrinfo(host, None)}
    except socket.gaierror as error:
        raise ValueError("Service hostname could not be resolved.") from error
    networks = [
        ipaddress.ip_network(item.strip())
        for item in get_settings().allowed_service_cidrs.split(",")
        if item.strip()
    ]
    for address in addresses:
        ip = ipaddress.ip_address(address)
        if allow_private_runner and any(ip in network for network in networks):
            continue
        if not allow_private_runner and ip.is_loopback:
            continue
        raise ValueError("Service address is outside the allowed private network.")


def claude_proxy_endpoint() -> dict | None:
    """Read the standalone Claude proxy's endpoint, or ``None`` when it is not up.

    The proxy picks a random port, so the only reliable way to learn it is the
    state file its launcher writes. Reading that file -- rather than storing a
    port in configuration -- is what keeps "the proxy is running" and "the
    backend knows where it is" the same fact instead of two that can disagree.

    The file is validated against a live connection before it is trusted. A
    launcher killed with SIGKILL never reaches its cleanup, so a stale file
    pointing at a dead port survives; believing it would turn every Worker turn
    into a connection timeout that looks like an upstream outage. A cheap TCP
    probe distinguishes "the file is stale" from "the proxy is up", which is the
    difference between falling back to the stored ``base_url`` and failing
    mysteriously.

    Returns the launcher's payload (``container_base_url``, ``token``, ...) or
    ``None`` when the proxy is absent, unreadable, or not actually listening.
    """

    raw = str(get_settings().claude_proxy_state_file or "").strip()
    return _read_proxy_state(raw)


def codex_proxy_endpoint() -> dict | None:
    """Read the standalone Codex Responses proxy's endpoint, or ``None``.

    The mirror of :func:`claude_proxy_endpoint`, and deliberately built on the
    same helper: the two proxies are separate processes on separate ports with
    separate state files, but the contract between launcher and reader -- what
    the file holds, and that a live TCP connection must confirm it -- is
    identical. Sharing the reader is what stops the Codex one from silently
    drifting from the Claude one (for example by trusting a stale file).

    ``None`` means "no proxy", and the caller must then fall back to the
    config's stored ``base_url`` -- the pre-proxy behaviour.
    """

    raw = str(get_settings().codex_proxy_state_file or "").strip()
    return _read_proxy_state(raw)


def _read_proxy_state(raw_path: str) -> dict | None:
    """Validate one proxy's state file, or return ``None`` if it is not usable.

    The liveness probe is the point.  A launcher killed with SIGKILL never
    reaches its cleanup, so a stale file pointing at a dead port survives;
    believing it would turn every Worker turn into a connection timeout that
    looks like an upstream outage.
    """

    if not raw_path:
        return None
    try:
        payload = json.loads(Path(raw_path).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    if not isinstance(payload, dict):
        return None
    port = payload.get("port")
    if not isinstance(port, int) or not _port_is_open(port):
        return None
    return payload


def _port_is_open(port: int, *, host: str = "127.0.0.1", timeout: float = 0.5) -> bool:
    """Whether something is listening on ``host:port`` right now.

    Checks the loopback rather than the launcher's advertised ``0.0.0.0``: a bind
    to all interfaces is reachable on loopback too, and loopback is the spelling
    that works regardless of which interface the proxy ended up on.
    """

    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
        probe.settimeout(timeout)
        return probe.connect_ex((host, port)) == 0
